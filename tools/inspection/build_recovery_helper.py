"""Build the single-file laptop helper from the tested backup/verifier sources."""
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
def build():
    verify=(ROOT/'tools/backup/verify.py').read_text().split("if __name__=='__main__':")[0]
    backup=(ROOT/'tools/backup/backup.py').read_text()
    backup=backup.replace('KEEP = int(ENV.get("KEEP_BACKUPS", "12"))','KEEP = 0  # One-time helper: never prune existing backups.')
    backup=backup.replace('DOWNLOAD_LIMIT = int(MAX_BACKUP_DOWNLOAD_MB * 1024 * 1024)',
                          'DOWNLOAD_LIMIT = int(min(MAX_BACKUP_DOWNLOAD_MB, 100) * 1024 * 1024)')
    backup=backup.replace('        from verify import verify\n','')
    backup=backup.replace('        prune(data_root)','        print("Older backups kept; scheduled task unchanged.")')
    backup=backup.replace('if __name__ == "__main__":\n    main()',
        '''if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        code = ("HTTP " + str(error.code)) if isinstance(error, urllib.error.HTTPError) else type(error).__name__
        print("Recovery check stopped (" + code + "). Older backups were kept. No cloud data changed.", file=sys.stderr)
        sys.exit(1)''')
    return ('#!/usr/bin/env python3\n# Generated by tools/inspection/build_recovery_helper.py. Do not edit this copy.\n'
            '# One-time private laptop backup: read-only cloud access, max 100 MiB response bodies, no pruning.\n'
            +verify+'\n'+backup)

if __name__=='__main__':
    (ROOT/'tools/backup/recovery_backup.py').write_text(build())
